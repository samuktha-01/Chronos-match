# ==============================================================================
# Latency-Instrumented Engine Proxy
# ==============================================================================


class LatencyInstrumentedEngine:
    """Transparent proxy delegating to a MatchingEngine while recording latency.

    Wraps the matching engine's `process_order()` method with high-resolution
    monotonic nanosecond timing (`time.perf_counter_ns()`) and writes duration
    samples directly into a `BoundedLatencyTracker`.

    Preserves 100% of underlying engine properties, order book structures,
    and Cython acceleration detection.
    """

    def __init__(
        self,
        target_engine: Any,
        latency_tracker: BoundedLatencyTracker,
    ) -> None:
        """Initialize LatencyInstrumentedEngine.

        Args:
            target_engine: Underlying MatchingEngine or CythonMatchingEngine instance.
            latency_tracker: Bounded reservoir receiving observed execution latencies.
        """
        self._target = target_engine
        self._tracker = latency_tracker

    def process_order(self, order: Order) -> list[Trade]:
        """Time and match order against the limit order book.

        Args:
            order: Order instance to process.

        Returns:
            List of Trade executions generated by the match.
        """
        start_ns = time.perf_counter_ns()
        try:
            trades = self._target.process_order(order)
            return trades
        finally:
            duration_ns = max(0.0, float(time.perf_counter_ns() - start_ns))
            self._tracker.record_latency(duration_ns)

    @property
    def target_engine(self) -> Any:
        """Underlying unwrapped matching engine instance."""
        return self._target

    @property
    def latency_tracker(self) -> BoundedLatencyTracker:
        """Underlying BoundedLatencyTracker instance."""
        return self._tracker

    @property
    def is_cython_accelerated(self) -> bool:
        """True only if underlying engine is a compiled native CythonMatchingEngine."""
        if not is_cython_compiled():
            return False
        target = self._target
        while hasattr(target, "target_engine"):
            target = target.target_engine
        from chronosmatch.cython_engine import _CompiledCythonMatchingEngine

        if _CompiledCythonMatchingEngine is not None:
            return isinstance(target, _CompiledCythonMatchingEngine)
        return False

    def __getattr__(self, name: str) -> Any:
        """Delegate all other attribute and method accesses to the underlying engine."""
        return getattr(self._target, name)


