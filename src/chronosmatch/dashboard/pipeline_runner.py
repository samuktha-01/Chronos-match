"""Pipeline Integration Layer for ChronosMatch Terminal Dashboard.

Bridges the real ChronosMatch trading pipeline (market feed simulator, shared-memory
IPC, lock-free ring buffer, binary protocol, and limit order book matching engine)
with the real-time terminal dashboard presentation layer.

Key Components:
- `LatencyInstrumentedEngine`: Transparent proxy around the matching engine that
  records nanosecond order execution latency into a `BoundedLatencyTracker` without
  blocking the critical matching path.
- `PipelineDashboardRunner`: Lifecycle controller and orchestrator managing concurrent
  pipeline execution and decoupled terminal dashboard rendering.
- `run_pipeline_with_dashboard`: High-level convenience entry point to run an
  end-to-end trading pipeline with real-time terminal dashboard visualization.
"""

