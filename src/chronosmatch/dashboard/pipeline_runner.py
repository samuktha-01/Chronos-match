def run_pipeline_with_dashboard(
    pipeline: TradingPipeline | None = None,
    *,
    total_orders: int | None = 5_000,
    rate: float | None = None,
    mode: SimulationMode | None = None,
    capacity: int = 1024,
    refresh_interval: float = 0.5,
    interactive: bool | None = None,
    use_colors: bool = True,
    use_unicode: bool | None = None,
    output: TextIO | None = None,
) -> TradingPipelineMetrics:
    """Run a ChronosMatch TradingPipeline with live TerminalDashboard telemetry.

    Args:
        pipeline: Existing TradingPipeline instance (creates new pipeline if None).
        total_orders: Number of orders to simulate and match.
        rate: Synthetic order generation rate in orders/second.
        mode: SimulationMode for arrival intervals (POISSON, UNIFORM, BURST, MAX_THROUGHPUT).
        capacity: RingBuffer slot capacity if creating a new pipeline.
        refresh_interval: Seconds between live dashboard refreshes.
        interactive: If True, uses cursor home codes; if False, prints streaming text; if None, auto-detects.
        use_colors: If True, applies ANSI color sequences.
        use_unicode: If True, uses Unicode borders; if None, auto-detects from stream.
        output: Destination stream (defaults to sys.stdout).

    Returns:
        Populated TradingPipelineMetrics from the completed simulation run.
    """
    if pipeline is None:
        config = MarketFeedConfig(
            total_orders=total_orders,
            rate=rate if rate is not None else 2000.0,
            mode=mode if mode is not None else SimulationMode.POISSON,
        )
        pipeline = create_pipeline(config=config, capacity=capacity)

    runner = PipelineDashboardRunner(
        pipeline=pipeline,
        refresh_interval=refresh_interval,
        interactive=interactive,
        use_colors=use_colors,
        use_unicode=use_unicode,
        output=output,
    )

    try:
        metrics = runner.run(total_orders=total_orders)
        return metrics
    finally:
        runner.close()
