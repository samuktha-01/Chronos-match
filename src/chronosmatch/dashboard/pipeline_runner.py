class PipelineDashboardRunner:
    """Orchestrates concurrent execution of a TradingPipeline with TerminalDashboard.

    Provides:
    - Decoupled, non-blocking telemetry collection via `DashboardMetricsCollector`.
    - Off-critical-path terminal UI rendering on a dedicated background worker thread.
    - Synchronous, step-by-step, and asynchronous pipeline execution modes.
    - Clean lifecycle management, error handling, and terminal restoration upon shutdown.
    - Safe handling of optional components (WAL, TradeStore, Cython, RingBuffer).
    """

    def __init__(
        self,
        pipeline: TradingPipeline | None = None,
        *,
        refresh_interval: float = 0.5,
        interactive: bool | None = None,
        use_colors: bool = True,
        use_unicode: bool | None = None,
        width: int = 80,
        output: TextIO | None = None,
        instrument_latency: bool = True,
        source_name: str | None = None,
    ) -> None:
        """Initialize PipelineDashboardRunner.

        Args:
            pipeline: Optional TradingPipeline instance (creates default if None).
            refresh_interval: Refresh interval in seconds for terminal rendering.
            interactive: If True, writes cursor control escape codes; if False, streams plain frames; if None, auto-detects.
            use_colors: If True, uses ANSI color escape sequences.
            use_unicode: If True, uses Unicode box drawing; if None, auto-detects from stream.
            width: Column width of dashboard box.
            output: Destination output stream (defaults to sys.stdout).
            instrument_latency: If True, enables latency instrumentation.
            source_name: Descriptive name for reporting (defaults to engine mode name).
        """
        self._owns_pipeline: bool = pipeline is None
        self._pipeline: TradingPipeline = pipeline if pipeline is not None else create_pipeline()

        self._instrument_latency = instrument_latency

        if self._instrument_latency:
            self._pipeline._instrument_latency = True
            if getattr(self._pipeline, "_core_latency_tracker", None) is None:
                self._pipeline._core_latency_tracker = BoundedLatencyTracker()
            if getattr(self._pipeline, "_dwell_latency_tracker", None) is None:
                self._pipeline._dwell_latency_tracker = BoundedLatencyTracker()
            if getattr(self._pipeline, "_tick_to_trade_tracker", None) is None:
                self._pipeline._tick_to_trade_tracker = BoundedLatencyTracker()

            self._core_latency_tracker = self._pipeline._core_latency_tracker
            self._dwell_latency_tracker = self._pipeline._dwell_latency_tracker
            self._tick_to_trade_tracker = self._pipeline._tick_to_trade_tracker
            self._latency_tracker = self._core_latency_tracker

            # Wrap engine with nanosecond latency instrumentation if not already wrapped
            if not isinstance(self._pipeline.engine, LatencyInstrumentedEngine):
                self._pipeline.engine = LatencyInstrumentedEngine(
                    self._pipeline.engine,
                    self._core_latency_tracker,
                )
        else:
            if hasattr(self._pipeline, "_instrument_latency"):
                self._pipeline._instrument_latency = False
            self._core_latency_tracker = BoundedLatencyTracker()
            self._dwell_latency_tracker = BoundedLatencyTracker()
            self._tick_to_trade_tracker = BoundedLatencyTracker()
            self._latency_tracker = self._core_latency_tracker

        resolved_source = (
            source_name
            if source_name is not None
            else ("ChronosMatch-Cython" if self._pipeline.is_cython_accelerated else "ChronosMatch-Pipeline")
        )

        self._collector = DashboardMetricsCollector(
            pipeline=self._pipeline,
            latency_tracker=self._core_latency_tracker,
            dwell_latency_tracker=self._dwell_latency_tracker,
            tick_to_trade_tracker=self._tick_to_trade_tracker,
            source_name=resolved_source,
        )

        self._dashboard = TerminalDashboard(
            collector=self._collector,
            refresh_interval=refresh_interval,
            interactive=interactive,
            use_colors=use_colors,
            use_unicode=use_unicode,
            width=width,
            output=output,
        )

    @property
    def pipeline(self) -> TradingPipeline:
        """Attached TradingPipeline instance."""
        return self._pipeline

    @property
    def collector(self) -> DashboardMetricsCollector:
        """Attached DashboardMetricsCollector instance."""
        return self._collector

    @property
    def dashboard(self) -> TerminalDashboard:
        """Attached TerminalDashboard instance."""
        return self._dashboard

    @property
    def latency_tracker(self) -> BoundedLatencyTracker:
        """Underlying core latency tracker instance (backward compatibility alias)."""
        return self._latency_tracker

    @property
    def core_latency_tracker(self) -> BoundedLatencyTracker:
        """Underlying core matching latency tracker instance."""
        return self._core_latency_tracker

    @property
    def dwell_latency_tracker(self) -> BoundedLatencyTracker:
        """Underlying queue dwell latency tracker instance."""
        return self._dwell_latency_tracker

    @property
    def tick_to_trade_tracker(self) -> BoundedLatencyTracker:
        """Underlying tick-to-trade latency tracker instance."""
        return self._tick_to_trade_tracker

    # --------------------------------------------------------------------------
    # Execution Modes
    # --------------------------------------------------------------------------

    def run(self, total_orders: int | None = None) -> TradingPipelineMetrics:
        """Run the pipeline to completion synchronously while updating the dashboard.

        Args:
            total_orders: Total orders to generate and process (None uses pipeline config).

        Returns:
            Populated TradingPipelineMetrics upon completion.
        """
        self._dashboard.start()
        try:
            metrics = self._pipeline.run_sync(total_orders=total_orders)
            return metrics
        finally:
            # Render final state to capture terminal completion snapshot
            try:
                self._dashboard.render_once()
            except Exception:
                pass
            self._dashboard.stop()

    async def run_async(self, total_orders: int | None = None) -> TradingPipelineMetrics:
        """Run the pipeline to completion asynchronously while updating the dashboard.

        Args:
            total_orders: Total orders to generate and process (None uses pipeline config).

        Returns:
            Populated TradingPipelineMetrics upon completion.
        """
        self._dashboard.start()
        try:
            metrics = await self._pipeline.run_async(total_orders=total_orders)
            return metrics
        finally:
            # Render final state to capture terminal completion snapshot
            try:
                self._dashboard.render_once()
            except Exception:
                pass
            self._dashboard.stop()

    def run_steps(self, count: int) -> list[Trade]:
        """Execute a deterministic number of simulated orders through the pipeline.

        Args:
            count: Number of orders to generate and match.

        Returns:
            List of Trade executions generated during the run.
        """
        all_trades: list[Trade] = []
        for _ in range(count):
            _, trades = self._pipeline.process_next_simulated_order()
            all_trades.extend(trades)

        try:
            self._dashboard.render_once()
        except Exception:
            pass

        return all_trades

    def process_order(self, order: Order) -> list[Trade]:
        """Manually push and process a single order through the pipeline.

        Args:
            order: Order instance to process.

        Returns:
            List of Trade executions generated by the order.
        """
        trades = self._pipeline.process_order(order)
        return trades

    # --------------------------------------------------------------------------
    # Lifecycle Management
    # --------------------------------------------------------------------------

    def stop(self) -> None:
        """Stop the running pipeline and dashboard background thread."""
        try:
            self._pipeline.stop()
        except Exception:
            pass
        self._dashboard.stop()

    def close(self) -> None:
        """Close dashboard and release pipeline resources if owned."""
        self._dashboard.stop()
        if self._owns_pipeline:
            self._pipeline.cleanup()

    def __enter__(self) -> Self:
        return self

    def __exit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        self.close()

    async def __aenter__(self) -> Self:
        return self

    async def __aexit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        self.close()


